// scripts/generate-seo-files.mjs
//
// Writes robots.txt and sitemap.xml into the build output directory.
//
// Run automatically by `npm run build` (after `vite build`) and by `npm run seo:files`.
// Generated rather than committed so the sitemap can never list routes the app does not
// have, and so both files use the same origin as the canonical tags.

import { writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { SITEMAP_PATHS, outputFileFor } from "./seo-routes.mjs";
import {
  distDir,
  siteOrigin,
  resolveSiteUrl,
  warnIfPlaceholder,
  assertProductionSiteUrl,
} from "./site-config.mjs";

const dist = distDir();

if (!existsSync(dist)) {
  console.error(
    `[seo] ${dist} does not exist. Run \`vite build\` before generating SEO files.`,
  );
  process.exit(1);
}

const { url: resolvedUrl, source } = resolveSiteUrl();

// A release build must never bake in a localhost or placeholder origin.
if (process.argv.includes("--production")) {
  assertProductionSiteUrl(resolvedUrl, source);
} else {
  warnIfPlaceholder(resolvedUrl, source);
}

const origin = siteOrigin();

// --- robots.txt -------------------------------------------------------------
// Login, registration and the authenticated dashboards are excluded from crawling.
// They are also served with noindex (see src/seo/SeoRoute.tsx), which is what actually
// removes them from the index; the Disallow rules here stop them being fetched at all.
// One deliberate exception: an asset URL that must be crawlable for rich previews
// should never be disallowed, so nothing under /assets/ is blocked.
const robots = `# robots.txt for ${origin}
# Generated by scripts/generate-seo-files.mjs — edit the script, not this file.

User-agent: *
Allow: /

# Authenticated areas and account pages: no search value, and crawling them
# only wastes crawl budget on a login wall.
Disallow: /dashboard
Disallow: /dashboard/
Disallow: /groups
Disallow: /groups/
Disallow: /login
Disallow: /register

# API endpoints are not pages. They are also disallowed on the API host itself; listed
# here because in the recommended single-origin deployment the API shares this domain.
Disallow: /auth/
Disallow: /users/
Disallow: /projects/
Disallow: /tasks/
Disallow: /social-links/
Disallow: /docs

# Crawl politely: this is a small community site.
Crawl-delay: 1

Sitemap: ${origin}/sitemap.xml
`;

// --- sitemap.xml ------------------------------------------------------------
const escapeXml = (value) =>
  value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");

const urls = SITEMAP_PATHS.map((path) => {
  const loc = `${origin}${path === "/" ? "/" : path}`;
  // Any stable value is acceptable; it never inflates ranking. Pointing every entry at
  // the newly built index.html reflects "this page was rebuilt in this release".
  const builtAt = existsSync(resolve(dist, outputFileFor(path)))
    ? new Date().toISOString().slice(0, 10)
    : undefined;

  return [
    "  <url>",
    `    <loc>${escapeXml(loc)}</loc>`,
    builtAt ? `    <lastmod>${builtAt}</lastmod>` : null,
    "    <changefreq>monthly</changefreq>",
    path === "/" ? "    <priority>1.0</priority>" : "    <priority>0.7</priority>",
    "  </url>",
  ]
    .filter(Boolean)
    .join("\n");
}).join("\n");

const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls}
</urlset>
`;

// --- write ------------------------------------------------------------------
for (const [name, contents] of [
  ["robots.txt", robots],
  ["sitemap.xml", sitemap],
]) {
  const target = resolve(dist, name);
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, contents, "utf8");
  console.log(`[seo] wrote ${target.replace(dist, "dist")}`);
}

console.log(`[seo] ${SITEMAP_PATHS.length} URLs in the sitemap for ${origin}`);
